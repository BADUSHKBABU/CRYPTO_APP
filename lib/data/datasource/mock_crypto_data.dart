  static List<ChartPointModel> generateMockChartPoints(double basePrice, int days) {
    final points = <ChartPointModel>[];
    final now = DateTime.now();
    final count = days == 1 ? 24 : (days == 7 ? 28 : (days == 30 ? 30 : 52));
    final durationStep = Duration(minutes: (days * 24 * 60 / count).round());

    double current = basePrice * 0.92;
    for (int i = 0; i < count; i++) {
      final time = now.subtract(durationStep * (count - i));
      // realistic small pseudo-random walk
      final variation = (i % 3 == 0 ? 0.012 : (i % 2 == 0 ? -0.008 : 0.015)) + ((i * 17 % 11) - 5) * 0.004;
      current = current * (1.0 + variation);
      points.add(ChartPointModel(timestamp: time, price: current));
    }
    // Ensure last point aligns with current price
    points.add(ChartPointModel(timestamp: now, price: basePrice));
    return points;
  }
